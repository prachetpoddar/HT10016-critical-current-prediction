     "Temperature axis, on the repaired 257-fit cohort: iron chalcogenide "
     "11-type 0.546, 122-type 0.580 and 1111-type 0.513 all fall below the "
     "screening-grade threshold of 1 in the exponent, against 0.588, 1.314 and "
     "3.120 as published; the threshold is absolute and the repairs compress "

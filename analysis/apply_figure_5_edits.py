"""
apply_figure_5_edits.py

Four edits to Figure 5 and its surrounding text, after the family parameters
were rebuilt.

Why. analysis/fit_family_params.py fitted the per-family parameters to the
dispatch table's own predictions, recovering the exponents the predictor had
used. That is circular, and under the refusal gates of this revision only the
MgB2 class has a non-refused row, so the module died with "expected non-empty
vector for x" and data/family_params.json was a frozen artifact from a cohort
state not present in the deposit. The old docstring's claim that reading the
parameters from the dispatch table is what let the figure be checked against
the withdrawals described a check that could not be run.

The parameters are now the family median exponents and the family median
partial anchor over the fitted cohorts, which is what the paper says the
predictor does at substructure-aggregate scope, and they are reproducible for
all three families. They move: the field exponent by between 0.20 and 0.26 and
the chalcogenide temperature exponent by 0.36. The envelopes move with them,
so the crossing the text and the caption both quote moves from a reduced field
of 0.59 to 0.58 and the gap at 0.9 from 0.40 dex to 0.69.

The caption's uncertainty band is also stated more plainly. The 0.31 dex
half-width is computed over the non-refused predictions, every one of which is
MgB2-class, and it is drawn identically around all three families. The caption
disclosed both facts in separate clauses; it now says so in one.

Usage:
    python3 analysis/apply_figure_5_edits.py IN_DIR OUT_DIR
"""
import os
import shutil
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from apply_compound_label_edits import (paragraphs, plain,          # noqa: E402
                                        replace_in_paragraph, unescape)

MAIN = "HT10016_revised_final25.docx"
SUPP = "SUPPLEMENTAL_MATERIAL_revised_final25.docx"
RESP = "RESPONSE_TO_REFEREES_final25.docx"
OUT = {MAIN: "HT10016_revised_final26.docx",
       SUPP: "SUPPLEMENTAL_MATERIAL_revised_final26.docx",
       RESP: "RESPONSE_TO_REFEREES_final26.docx"}

EDITS = [
    # ---- 1. Sec. III.E, the crossing -----------------------------------
    (MAIN,
     "Iron chalcogenide 11-type and iron pnictide 122-type cross at a reduced "
     "field of 0.59, above which the 122-type envelope is the higher of the "
     "two, by 0.40 dex at a reduced field of 0.9 (Fig. 5).",

     "Iron chalcogenide 11-type and iron pnictide 122-type cross at a reduced "
     "field of 0.58, above which the 122-type envelope is the higher of the "
     "two, by 0.69 dex at a reduced field of 0.9 (Fig. 5)."),

    # ---- 2. the caption's crossing -------------------------------------
    (MAIN,
     "The cross in panel (b) marks the reduced field of 0.59 at which the "
     "iron chalcogenide and iron pnictide envelopes cross",

     "The cross in panel (b) marks the reduced field of 0.58 at which the "
     "iron chalcogenide and iron pnictide envelopes cross"),

    # ---- 3. the caption's uncertainty band -----------------------------
    (MAIN,
     "Shaded envelopes are drawn at a constant half-width of 0.31 dex around "
     "each curve, which is half the median full width of the 95% bootstrap "
     "confidence interval quoted as 0.61 dex in the text (5000 iterations) "
     "across non-refused predictions; per-grid-point intervals are narrower "
     "in low-uncertainty regions and wider elsewhere.",

     "Shaded envelopes are drawn at a constant half-width of 0.31 dex around "
     "each curve. That is half the median full width of the 95% bootstrap "
     "confidence interval quoted as 0.61 dex in the text (5000 iterations) "
     "across the non-refused predictions, every one of which is MgB2-class, "
     "so one family's uncertainty is drawn around all three and the two "
     "envelopes that dispatch nothing carry no uncertainty of their own. "
     "Within the dispatched set the per-grid-point half-width is 0.30 dex at "
     "4.2 K and 0.41 dex at 20 K."),

    # ---- 4. the caption's provenance for the parameters ----------------
    (MAIN,
     "(a) Predicted temperature dependence of log10 Jc at a fixed reduced "
     "field H/Hc2,0 = 0.5, against reduced temperature T/Tc.",

     "Each family's exponents are its median fitted exponent on each axis and "
     "its median partial critical-current anchor, over the admitted field-axis "
     "cohort and the repaired temperature-axis cohort, regenerated by "
     "analysis/fit_family_params.py. (a) Predicted temperature dependence of "
     "log10 Jc at a fixed reduced field H/Hc2,0 = 0.5, against reduced "
     "temperature T/Tc."),
]


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: apply_figure_5_edits.py IN_DIR OUT_DIR")
    src, dst = sys.argv[1], sys.argv[2]
    os.makedirs(dst, exist_ok=True)
    by_file = {}
    for f, find, repl in EDITS:
        by_file.setdefault(f, []).append((find, repl))
    for name in (MAIN, SUPP, RESP):
        ip, op = os.path.join(src, name), os.path.join(dst, OUT[name])
        if not os.path.exists(ip):
            sys.exit("missing input: %s" % ip)
        zin = zipfile.ZipFile(ip)
        doc = zin.read("word/document.xml").decode("utf-8")
        for find, repl in by_file.get(name, []):
            hits = [p for p in paragraphs(doc) if find in unescape(plain(p))]
            if len(hits) != 1:
                sys.exit("%s: %d paragraph(s) contain %r, expected exactly 1"
                         % (name, len(hits), find[:70]))
            new = replace_in_paragraph(hits[0], find, repl)
            if new is None:
                sys.exit("%s: could not place the replacement for %r"
                         % (name, find[:70]))
            doc = doc.replace(hits[0], new, 1)
            print("   %-8s %s" % (name.split("_")[0][:8], find[:62]))
        tmp = op + ".part"
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                if item.filename == "word/document.xml":
                    zout.writestr(item, doc)
                else:
                    zout.writestr(item, zin.read(item.filename))
        zin.close()
        shutil.move(tmp, op)
        print("   wrote %s" % op)
    return 0


if __name__ == "__main__":
    sys.exit(main())

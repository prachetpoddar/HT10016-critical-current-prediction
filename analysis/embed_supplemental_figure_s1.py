"""
embed_supplemental_figure_s1.py

Puts Supplemental Figure S1 into the Supplemental Material.

It has never been there. analysis/manuscript_figure_s1_extraction_examples.py
has written figures/figure_S1_extraction_examples.png since 2026-09-02, the
manuscript's own Figure 4 generator refers to it by name, and no document
contains it or refers to a supplementary figure at all. The supplement carried
zero images.

It could not have been regenerated either. Its middle panel drew
s41467-025-55880-4 at 53 K, and that paper was withdrawn from the field axis
after it was read: audit/withdraw_s41467_field_axis.md records that it reports
critical currents in microamps over sweeps to 25 millitesla and contains the
string "current density" zero times, so the six field-axis fits attributed to
it are not readings of it. Its rows left the fit table with the withdrawal and
the generator has died on a missing fit ever since. Nothing noticed, because
nothing rendered it.

The panel now draws j.jallcom.2013.04.183 sample N1 at 10 K, a live record of
the same kind: seven points over 0 to 1.5 T against a literature 100 T scale, a
span of 0.015, and a fit at the numerical ceiling of 30 with a standard error
of 28.6, larger than the estimate. Its seven extracted points are deposited at
data/extraction_examples/jallcom_2013_04_183_field_axis.csv in the same schema
as the two that were already there.

The figure goes into Section 15, which is the section Referee A's request for
examples produced, immediately after that section's opening paragraph and
before the tables. The caption states what each panel is and names the
withdrawal that forced the replacement.

Usage:
    python3 analysis/embed_supplemental_figure_s1.py IN_DIR OUT_DIR
"""
import os
import shutil
import sys

FIG = os.path.join("figures", "figure_S1_extraction_examples.png")
IN_NAMES = ("HT10016_revised_final30.docx",
            "SUPPLEMENTAL_MATERIAL_revised_final30.docx",
            "RESPONSE_TO_REFEREES_final30.docx")
OUT_NAMES = ("HT10016_revised_final31.docx",
             "SUPPLEMENTAL_MATERIAL_revised_final31.docx",
             "RESPONSE_TO_REFEREES_final31.docx")
SUPP = 1

ANCHOR = "15. Worked examples from the deposited dataset"
# The figure goes after the section's opening paragraph, not between the
# heading and it: inserting at the heading put the figure above the sentence
# that introduces the section.
OPENING = "Referee A asked for examples of the extracted data."
CAPTION = (
    "FIG. S1. Three worked extraction-to-fit examples, one per outcome, drawn "
    "from the deposited extraction files under data/extraction_examples and "
    "from the deposited Form 3 fit table. Open circles are extracted points "
    "the fit did not use, filled circles the points it did, the shaded band "
    "the fitted field span, and the line the fit the paper reports rather than "
    "a refit. (a) Retained: FeTe0.59Se0.41 at 2 K from j.physc.2010.05.048, "
    "with a critical field resolved at the measurement temperature, a span of "
    "0.571 of that scale and a field exponent of 0.107 with a standard error "
    "of 0.018. (b) At the applicability bound: Bi-2223 sample N1 at 10 K from "
    "j.jallcom.2013.04.183, seven points over 0 to 1.5 T against a literature "
    "100 T scale, a span of 0.015, and a fit at the numerical ceiling of 30 "
    "with a standard error of 28.6, larger than the estimate. This is the "
    "failure mode Sec. III.F of the main text describes. (c) Withdrawn: "
    "FeTe0.61Se0.39 at 2 K from j.physc.2010.03.003, five points falling by "
    "exactly 0.500 dex each across field intervals of 4.5, 10, 10 and 25 T. A "
    "reading of a printed curve cannot produce a constant factor between "
    "points that is independent of how far the field moved, and this record is "
    "withdrawn on that ground. An earlier version of this figure used "
    "s41467-025-55880-4 for panel (b); that paper's field-axis fits are "
    "withdrawn, for the reason given in the deposit, and a live record of the "
    "same kind replaces it. Regenerated by "
    "analysis/manuscript_figure_s1_extraction_examples.py."
)
WIDTH_IN = 6.5


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: embed_supplemental_figure_s1.py IN_DIR OUT_DIR")
    src, dst = sys.argv[1], sys.argv[2]
    if not os.path.exists(FIG):
        sys.exit("missing %s; run its generator first" % FIG)
    os.makedirs(dst, exist_ok=True)
    for a, b in zip(IN_NAMES, OUT_NAMES):
        ip = os.path.join(src, a)
        if not os.path.exists(ip):
            sys.exit("missing input: %s" % ip)
        shutil.copy(ip, os.path.join(dst, b))

    import docx
    from docx.shared import Inches
    path = os.path.join(dst, OUT_NAMES[SUPP])
    d = docx.Document(path)
    if any("FIG. S1" in p.text for p in d.paragraphs):
        sys.exit("the supplement already carries a Figure S1 caption")
    hits = [i for i, p in enumerate(d.paragraphs)
            if p.text.strip() == ANCHOR]
    if len(hits) != 1:
        sys.exit("found %d paragraphs equal to %r, expected exactly 1"
                 % (len(hits), ANCHOR))
    opens = [i for i, p in enumerate(d.paragraphs)
             if p.text.strip().startswith(OPENING)]
    if len(opens) != 1:
        sys.exit("found %d paragraphs opening with %r, expected exactly 1"
                 % (len(opens), OPENING))
    if opens[0] < hits[0]:
        sys.exit("the section's opening paragraph precedes its heading; the "
                 "document is not laid out the way this insertion assumes")
    if opens[0] + 1 >= len(d.paragraphs):
        sys.exit("the section's opening paragraph is the last in the "
                 "document; there is nothing to insert before")
    # After the heading and its opening paragraph, before the tables.
    after = d.paragraphs[opens[0] + 1]

    fig_p = after.insert_paragraph_before()
    fig_p.add_run().add_picture(FIG, width=Inches(WIDTH_IN))
    cap_p = after.insert_paragraph_before(CAPTION)
    cap_p.style = after.style
    # insert_paragraph_before puts both above `after`, so the figure precedes
    # its caption only if it was inserted first, which it was.
    d.save(path)

    z = docx.Document(path)
    n_img = len(z.inline_shapes)
    if n_img != 1:
        sys.exit("the supplement now holds %d inline image(s), expected 1"
                 % n_img)
    print("   inserted Figure S1 and its caption into Section 15 of %s"
          % os.path.basename(path))
    print("   the supplement now holds %d inline image" % n_img)
    for a, b in zip(IN_NAMES, OUT_NAMES):
        print("   wrote %s" % os.path.join(dst, b))
    return 0


if __name__ == "__main__":
    sys.exit(main())

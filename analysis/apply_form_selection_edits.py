"""
apply_form_selection_edits.py

Three edits to Sec. II.C and the Table II caption, after the functional-form
comparison was rebuilt.

Why. Table II selects Form 3 for the whole paper, and four things about it were
wrong. Its generator was not in the deposit. Its holdout was drawn point by
point inside a compound, so every held-out point sits on a curve whose other
points trained the model, which is the pooling Sec. II.B rejects in writing.
Its caption said "identical splits across forms", and the original consumes one
random stream inside the form loop, so each form draws a different permutation:
measured over the 23 fittable compounds, none has identical Form 1 and Form 3
holdout sets and every overlap sits at the chance rate. And because the three
forms also filter to different frames, they were scored on different rows and
on different numbers of compounds, with Form 2 scored on one fewer compound
than the others, the one carrying the smallest Form 3 error in the cohort.

analysis/functional_form_comparison.py rebuilds it. It deposits the fitter's
input and the original's own per-compound output, reproduces the latter on all
23 compounds to a worst relative disagreement of 1.7e-8 before reporting
anything, and then scores the three forms on identical training and holdout
rows over twenty seeds per compound.

What the rebuild shows, on the post-withdrawal cohort:

  * Form 3 beats Form 1 on 14 of 15 compounds under a point-level split and 11
    of 13 under a curve-level split, at exact two-sided sign probabilities of
    0.001 and 0.022. The direction holds at exponent bounds of 10, 50 and 200
    and on the cohort as published.
  * Form 3 does not separate from Form 2: 11 of 15 and 9 of 13, at 0.118 and
    0.267. The published margin of 0.092 dex is 0.012 once all three forms are
    scored on the same compounds.
  * Under a source-paper holdout no form reaches a median below 0.9 dex.

So the empirical basis Sec. II.C cited for choosing Form 3 over Form 2 is not
there, while the basis over Form 1 is. The reason to prefer Form 3 is that it
is the only one of the three that separates the two dependences into exponents
that can be fitted and reported per axis, which every later stage requires.
That is what the section now says.

Table II's printed values are kept. They reproduce, and they are the original
comparison; what changes is a caption that described them wrongly.

Usage:
    python3 analysis/apply_form_selection_edits.py IN_DIR OUT_DIR
"""
import os
import shutil
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from apply_compound_label_edits import (paragraphs, plain,          # noqa: E402
                                        replace_in_paragraph, unescape)

MAIN = "HT10016_revised_final23.docx"
SUPP = "SUPPLEMENTAL_MATERIAL_revised_final23.docx"
RESP = "RESPONSE_TO_REFEREES_final23.docx"
OUT = {MAIN: "HT10016_revised_final24.docx",
       SUPP: "SUPPLEMENTAL_MATERIAL_revised_final24.docx",
       RESP: "RESPONSE_TO_REFEREES_final24.docx"}

EDITS = [
    # ---- 1. the selection sentence -------------------------------------
    (MAIN,
     "Their per-paper holdout mean absolute errors in log10 Jc are 0.597, "
     "0.352, and 0.260 dex respectively, and Form 3 was adopted on that "
     "empirical basis.",

     "We adopt Form 3 because it is the only one of the three that separates "
     "the temperature and field dependences into exponents that can be fitted "
     "and reported on each axis independently, which every later stage of "
     "this work requires. The holdout comparison supports that choice against "
     "Form 1 and does not separate it from Form 2. Scoring the three forms on "
     "identical training and holdout rows, over twenty random splits per "
     "compound, Form 3 has the lower error on 14 of 15 compounds against Form "
     "1 under a point-level split and on 11 of 13 under a curve-level split, "
     "at exact two-sided sign probabilities of 0.001 and 0.022. Against Form "
     "2 it leads on 11 of 15 and on 9 of 13, at 0.118 and 0.267, which is not "
     "a separation. The values in Table II, 0.597, 0.352 and 0.260 dex, were "
     "computed with a separate random split for each form and over different "
     "numbers of compounds; on the compounds all three forms can score, the "
     "margin between Forms 2 and 3 is 0.012 dex rather than 0.092. Under a "
     "source-paper holdout, in which every measurement of a held-out source "
     "is withheld, no form reaches a median error below 0.9 dex on the eight "
     "compounds drawing on more than one source. The comparison is "
     "regenerated by analysis/functional_form_comparison.py from the "
     "deposited input."),

    # ---- 2. the Table II caption ---------------------------------------
    (MAIN,
     "TABLE II. Functional-form comparison on the fully fittable cohort. "
     "Per-paper holdout mean absolute error in log10 Jc, 80/20 split per "
     "compound, identical splits across forms.",

     "TABLE II. Functional-form comparison on the fully fittable cohort. "
     "Median per-compound holdout mean absolute error in log10 Jc, from an "
     "80/20 point-level split drawn within each compound. The splits were "
     "drawn separately for each form, so the three columns are not scored on "
     "the same held-out points, and the point-level split places measurements "
     "of one compound in both the training and the held-out set. Sec. II.C "
     "gives the comparison on identical rows and under holdouts that withhold "
     "whole curves and whole sources."),

    # ---- 3. the cross-reference in Sec. II.C ---------------------------
    (MAIN,
     "Form 3 was selected on the holdout comparison in Table II, evaluated "
     "per paper on the fully fittable cohort.",

     "Form 3 was selected for the separability set out above rather than on "
     "the margin in Table II, which is evaluated per compound and not per "
     "paper on the fully fittable cohort."),
]


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: apply_form_selection_edits.py IN_DIR OUT_DIR")
    src, dst = sys.argv[1], sys.argv[2]
    os.makedirs(dst, exist_ok=True)
    by_file = {}
    for f, find, repl in EDITS:
        by_file.setdefault(f, []).append((find, repl))
    for name in (MAIN, SUPP, RESP):
        ip, op = os.path.join(src, name), os.path.join(dst, OUT[name])
        if not os.path.exists(ip):
            sys.exit("missing input: %s" % ip)
        zin = zipfile.ZipFile(ip)
        doc = zin.read("word/document.xml").decode("utf-8")
        for find, repl in by_file.get(name, []):
            hits = [p for p in paragraphs(doc) if find in unescape(plain(p))]
            if len(hits) != 1:
                sys.exit("%s: %d paragraph(s) contain %r, expected exactly 1"
                         % (name, len(hits), find[:70]))
            new = replace_in_paragraph(hits[0], find, repl)
            if new is None:
                sys.exit("%s: could not place the replacement for %r"
                         % (name, find[:70]))
            doc = doc.replace(hits[0], new, 1)
            print("   %-8s %s" % (name.split("_")[0][:8], find[:62]))
        tmp = op + ".part"
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                if item.filename == "word/document.xml":
                    zout.writestr(item, doc)
                else:
                    zout.writestr(item, zin.read(item.filename))
        zin.close()
        shutil.move(tmp, op)
        print("   wrote %s" % op)
    return 0


if __name__ == "__main__":
    sys.exit(main())
